#!/usr/bin/env node
'use strict';
const A=require('node:assert/strict');
const R=require('../assets/water-ripples/src/ripples-core.js');
const cp=o=>JSON.parse(JSON.stringify(o));
const c=R.defaults();
A.equal(R.VERSION,1);A.equal(c.schemaVersion,1);
A.equal(c.durationFrames,40);A.equal(c.exportFrames,40);
A.equal(c.loop,false);A.equal(c.rings,3);
A.equal(c.startRadius,5);A.equal(c.finalRadius,120);
A.equal(c.ringDelayFrames,7);A.equal(c.radialGapPx,20);
A.equal(c.thickness,3);A.equal(c.ellipticity,1);
A.equal(c.seed,83291);
A.equal(c.palette.stops[0].rgba[0],226);
A.equal(c.palette.stops[1].rgba[1],190);
A.deepEqual(R.LAYERS,['primary','secondary','highlights']);
A.deepEqual(Object.keys(c.emitters[0].layers),R.LAYERS);
A.ok(Object.keys(c.emitters[0].layers).every(key=>'anchor' in c.emitters[0].layers[key]));
A.equal(c.emitters[0].layers.highlights.enabled,false);
const events=R.schedule(c,c.emitters[0]);
A.equal(events.length,3);
A.ok(Math.abs(events[0].time)<1e-8);
A.ok(Math.abs(events[1].time-7/60)<.00001);
A.ok(Math.abs(events[2].time-14/60)<.00001);
const first=R.sample(c,0);
A.equal(first.emitters[0].layers.primary.length,1);
A.equal(first.emitters[0].layers.secondary.length,0);
A.equal(first.emitters[0].layers.highlights.length,0);
const one=first.emitters[0].layers.primary[0];
A.equal(one.kind,'ring');
A.ok(Math.abs(one.radiusX-5)<.0001);
A.ok(Math.abs(one.radiusY-5)<.0001);
const f7=R.sample(c,7/60).emitters[0].layers;
A.equal(f7.primary.length,1);A.equal(f7.secondary.length,1);
A.ok(Math.abs(f7.secondary[0].radiusX-25)<.001);
const f14=R.sample(c,14/60).emitters[0].layers;
A.equal(f14.primary.length,1);A.equal(f14.secondary.length,2);
A.ok(Math.abs(f14.secondary[1].radiusX-45)<.001);
const fade=R.sample(c,38/60);
const end=R.sample(c,39/60);
A.ok(fade.emitters[0].layers.primary[0].rgba[3]>0);
A.ok(end.emitters.every(e=>R.LAYERS.every(k=>e.layers[k].length===0)));
A.ok(R.sample(c,40/60).emitters.every(e=>R.LAYERS.every(k=>e.layers[k].length===0)));
const cyclic=cp(c);cyclic.loop=true;
const cycleStart=R.sample(cyclic,0);
A.deepEqual(R.sample(cyclic,40/60),cycleStart);
A.ok(cycleStart.emitters[0].layers.secondary.length>=1,
 'repeat mode must carry prior-cycle rings with no global reset');
const gap=cp(c);gap.radialGapPx=34;
A.deepEqual(R.schedule(gap,gap.emitters[0]),events);
const gap0=R.sample(gap,14/60).emitters[0].layers.secondary[1];
A.equal(gap0.radiusX-f14.secondary[1].radiusX,28);
const late=cp(c);late.ringDelayFrames=10;
const lateSchedule=R.schedule(late,late.emitters[0]);
A.ok(Math.abs(lateSchedule[1].time-10/60)<.00001);
A.notDeepEqual(lateSchedule,events);
const delayCurve=cp(c);delayCurve.ringDelayCurve.keys[1].y=.5;
A.notDeepEqual(R.schedule(delayCurve,delayCurve.emitters[0]),events);
const radiusCurve=cp(c);radiusCurve.radiusCurve.keys[1].y=.3;
A.notDeepEqual(R.sample(radiusCurve,20/60),R.sample(c,20/60));
const thickCurve=cp(c);thickCurve.thicknessCurve.keys[1].y=.8;
A.notDeepEqual(R.sample(thickCurve,20/60),R.sample(c,20/60));
const alphaCurve=cp(c);alphaCurve.ringAlphaCurve.keys[1].y=.2;
A.notDeepEqual(R.sample(alphaCurve,20/60),R.sample(c,20/60));
const ellipse=cp(c);ellipse.ellipticity=2;
const ellipseRing=R.sample(ellipse,0).emitters[0].layers.primary[0];
A.ok(Math.abs(ellipseRing.radiusX/ellipseRing.radiusY-2)<1e-8);
A.ok(Math.abs(ellipseRing.radiusX*ellipseRing.radiusY-25)<1e-8);
const zero=cp(c);zero.startRadius=0;
A.doesNotThrow(()=>R.sample(zero,0));
const highlight=cp(c);highlight.emitters[0].layers.highlights.enabled=true;
const h=R.sample(highlight,15/60).emitters[0].layers.highlights;
A.ok(h.length>4);
A.ok(h.every(v=>v.kind==='highlight'&&Number.isFinite(v.x)&&Number.isFinite(v.y)));
const spac=cp(highlight);spac.highlightArcGapPx=30;
A.notDeepEqual(R.sample(spac,15/60).emitters[0].layers.highlights,h);
const dist=cp(highlight);dist.highlightDistribution='clustered';
A.notDeepEqual(R.sample(dist,15/60).emitters[0].layers.highlights,h);
const seeded=cp(highlight);seeded.seed++;
A.notDeepEqual(R.sample(seeded,15/60).emitters[0].layers.highlights,h);
for(const at of [0,1/60,5/60,13/60,30/60]){
 A.deepEqual(R.sample(c,at),R.sample(c,at));
 A.deepEqual(R.sample(c,at),R.sample(c,Math.round(at*60)/60));
}
const two=cp(c);two.emitters.push(R.newEmitter(1));
A.equal(R.sample(two,.3).emitters.length,2);
A.deepEqual(R.sample(two,.3).emitters[0],R.sample(c,.3).emitters[0]);
two.emitters.reverse();
A.deepEqual(R.sample(two,.3).emitters.find(e=>e.id==='emitter1'),R.sample(c,.3).emitters[0]);
const disabled=cp(c);
for(const layer of Object.values(disabled.emitters[0].layers))layer.enabled=false;
A.ok(R.sample(disabled,.3).emitters.every(e=>R.LAYERS.every(k=>e.layers[k].length===0)));
const all=cp(c);all.rings=12;all.ringDelayFrames=60;
A.throws(()=>R.normalize(all),/schedule|40|duration|birth|window/i);
A.throws(()=>R.normalize({...c,extra:1}),/unknown/i);
A.throws(()=>R.normalize({...c,schemaVersion:2}),/version/i);
A.throws(()=>R.normalize({...c,rings:13}),/rings/i);
A.throws(()=>R.normalize({...c,finalRadius:4}),/radius/i);
A.throws(()=>R.normalize({...c,emitters:[c.emitters[0],c.emitters[0]]}),/duplicate/i);
const count=cp(c);count.ringDelayFrames=0;count.rings=12;
A.equal(R.schedule(count,count.emitters[0]).length,12);
A.ok(R.schedule(count,count.emitters[0]).every(e=>e.time===0));
const crop=cp(c);crop.emitters[0].anchor.x=0;
A.equal(R.bounds(R.sample(crop,20/60),crop).inside,false);
console.log('PASS WATER-03 NUMERIC 40f one-shot/carry-loop, ring births 0/7/14, independent radial gap/delay, 4 curves, elliptical geometry, highlights, 4-emitter independence, strict schema/budgets');
